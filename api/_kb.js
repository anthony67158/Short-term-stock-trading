// 拼成可检索文档（供 retrieve 使用）
export function kbDocs() {
  return KB.map((k, i) => ({
    type: 'theory',
    id: i,
    book: k.book,
    topic: k.topic,
    text: `【${k.book}·${k.topic}】${k.text}`,
  }));
}

// ---------- 理论 RAG 检索（向量优先，关键词兜底；温实例内缓存向量）----------
import { embed, cosine } from './_rag.js';

let _vecCache = null; // 缓存 KB 向量，避免每次请求重复 embedding

async function ensureVectors() {
  if (_vecCache) return _vecCache;
  const docs = kbDocs();
  try {
    const vecs = await embed(docs.map((d) => d.text));
    if (vecs && vecs.length === docs.length) {
      _vecCache = docs.map((d, i) => ({ ...d, vec: vecs[i] }));
      return _vecCache;
    }
  } catch { /* 嵌入失败则退化关键词 */ }
  _vecCache = docs.map((d) => ({ ...d, vec: null }));
  return _vecCache;
}

// 检索与 query 最相关的 k 条投资理论
export async function retrieveTheory(query, k = 4) {
  const store = await ensureVectors();
  const hasVec = store[0] && store[0].vec;
  if (hasVec) {
    try {
      const [qv] = await embed([query]);
      if (qv) {
        const scored = store
          .map((d) => ({ book: d.book, topic: d.topic, text: d.text, score: cosine(qv, d.vec) }))
          .sort((a, b) => b.score - a.score);
        return scored.slice(0, k);
      }
    } catch { /* fallthrough */ }
  }
  // 关键词兜底
  const kw = String(query).split(/\s+|[，,。、；;]/).filter((w) => w.length >= 2);
  const scored = store
    .map((d) => ({ book: d.book, topic: d.topic, text: d.text, score: kw.reduce((s, w) => s + (d.text.includes(w) ? 1 : 0), 0) }))
    .sort((a, b) => b.score - a.score);
  return scored.slice(0, k);
}
